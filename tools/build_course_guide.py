"""Builds site/course-guide.html and bot/answer-hub-articles.md from site/courses.js.

The guide is plain HTML (no JavaScript), so SalesIQ's web-page training and
search engines can read every course's details and "try instead" advice.
Run after editing courses.js:  python tools/build_course_guide.py
"""

import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://academy.lms-mark.website"


def load_courses() -> list[dict]:
    text = (ROOT / "site" / "courses.js").read_text(encoding="utf-8")
    body = text[text.index("[", text.index("window.COURSES")) : text.index("];") + 1]
    body = re.sub(r"//.*", "", body)                       # drop comments
    body = re.sub(r"(\n\s*)(\w+):", r'\1"\2":', body)       # quote keys
    body = re.sub(r",(\s*[}\]])", r"\1", body)              # trailing commas
    return json.loads(body)


def price(n: int) -> str:
    return "₹" + f"{n:,}"


def build() -> None:
    courses = load_courses()
    by_id = {c["id"]: c for c in courses}
    e = html.escape

    cards, articles = [], []
    for c in courses:
        alts = []
        for item in c["tryInstead"]:
            alt_id, reason = item.split("|", 1)
            alt = by_id[alt_id]
            alts.append((alt, reason))
        url = f"{SITE}/course.html?id={c['id']}"
        cards.append(f"""
    <article class="panel guide-course" id="{e(c['id'])}">
      <h2>{e(c['title'])}</h2>
      <p class="meta">{e(c['level'])} · {e(c['duration'])} · {c['lessons']} lessons · {price(c['price'])} · certificate included</p>
      <p><strong>Topic:</strong> {e(c['goal'])}</p>
      <p>{e(c['summary'])}</p>
      <p><strong>Who it's for:</strong> {e(c['audience'])}</p>
      <p><strong>You will learn:</strong> {e('; '.join(c['outcomes']))}.</p>
      <p><strong>Not the right fit? Try instead:</strong></p>
      <ul>{''.join(f'<li><a href="#{e(a["id"])}">{e(a["title"])}</a>: {e(r)}.</li>' for a, r in alts)}</ul>
      <p><a href="{e(url)}">View course page</a></p>
    </article>""")
        articles.append(
            f"## {c['title']}\n\n"
            f"**Title for Answer Hub:** {c['title']}: who it's for and what to try instead\n\n"
            f"{c['title']} is a {c['level'].lower()} course on {c['goal'].lower()}: {c['summary']} "
            f"It takes {c['duration']} over {c['lessons']} lessons and costs {price(c['price'])}, with a certificate on completion.\n\n"
            f"Who it's for: {c['audience']}\n\n"
            f"You will learn: {'; '.join(c['outcomes'])}.\n\n"
            "If this course isn't useful for you, try:\n"
            + "".join(f"- {a['title']} ({a['duration']}, {price(a['price'])}): {r}.\n" for a, r in alts)
            + f"\nCourse page: {url}\n"
        )

    picker = "".join(
        f"<li><strong>{e(c['goal'])}</strong>: {e(c['title'])} ({e(c['level'])}, {e(c['duration'])})</li>"
        for c in courses
    )
    page = f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Course guide · LMS-Mark Academy</title>
  <meta name="description" content="Every LMS-Mark Academy course: who it's for, what you learn, price, and which course to try instead.">
  <link rel="stylesheet" href="styles.css?v=9">
  <script src="zoho-config.js?v=9"></script>
  <script src="courses.js?v=9"></script>
  <script src="app.js?v=9"></script>
</head>
<body data-page="guide">
  <header id="site-header"></header>
  <!-- Generated by tools/build_course_guide.py from courses.js. Do not edit by hand. -->
  <main class="wrap prose">
    <h1>Course guide</h1>
    <p>Not sure where to start, or a course isn't quite right for you? Pick by what you want to get better at:</p>
    <ul>{picker}</ul>
    <p>All courses are self-paced video lessons with a short quiz and a certificate on completion, with lifetime access.</p>
    {''.join(cards)}
  </main>
  <footer id="site-footer"></footer>
</body>
</html>
"""
    (ROOT / "site" / "course-guide.html").write_text(page, encoding="utf-8")

    chooser = (
        "## Which course should I choose?\n\n"
        "**Title for Answer Hub:** Which LMS-Mark Academy course should I choose?\n\n"
        "Choose by what you want to get better at:\n"
        + "".join(f"- {c['goal']}: {c['title']} ({c['level']}, {c['duration']}, {price(c['price'])})\n" for c in courses)
        + f"\nShortest and cheapest: Basic Life Support Refresher (3 hours, ₹799). Full guide: {SITE}/course-guide.html\n"
    )
    out = ROOT / "bot"
    out.mkdir(exist_ok=True)
    (out / "answer-hub-articles.md").write_text(
        "# Answer Hub articles for the SalesIQ bot\n\nGenerated from site/courses.js. Paste each section into "
        "SalesIQ → Answer Hub → Articles → Compose, using the title shown.\n\n" + chooser + "\n" + "\n".join(articles),
        encoding="utf-8",
    )
    print(f"wrote site/course-guide.html and bot/answer-hub-articles.md ({len(courses)} courses)")


if __name__ == "__main__":
    build()
